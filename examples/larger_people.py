PERSON_SURVEY_SYSTEM_PROMPT = """
You are simulating a fictional person completing a housing-preference survey.

Answer the survey as the person described in the user prompt. Use only the
person's description and reasonable common-sense inferences from it.

This survey is being completed independently before the person sees any houses.
Do not mention or evaluate specific houses. Do not use information from any
other person.

Return exactly one valid JSON object.

The JSON object must:
1. Contain exactly one key for each survey question.
2. Use the question IDs as keys.
3. Use a plain text string as the value for every key.
4. Contain no nested dictionaries or arrays.
5. Contain no Markdown, code fences, or explanatory text outside the JSON object.
"""


def build_person_survey_prompt(
    *,
    person: dict[str, str],
    survey
) -> str:
    """
    Build the complete prompt for one person.

    This prompt contains no house information and no previous conversation.
    """

    question_text = "\n\n".join(
        f"{index}. Question ID: {question.id}\n"
        f"Question: {question.text}"
        for index, question in enumerate(survey.questions, start=1)
    )

    question_ids = [question.id for question in survey.questions]

    return f"""
Complete the following housing-preference survey as this fictional person.

PERSON ID:
{person["id"]}

PERSON NAME:
{person["name"]}

PERSON DESCRIPTION:
{person["description"]}

SURVEY QUESTIONS:
{question_text}

REQUIRED JSON KEYS:
{json.dumps(question_ids, indent=2)}

Return exactly one JSON object with those keys. Every value must be a plain
text string. Return no Markdown and no additional commentary.
"""


def extract_json_object(text: str) -> dict[str, Any]:
    """
    Parse a JSON object from an LLM response.

    The first attempt expects strict JSON. The fallback handles accidental
    surrounding text or Markdown fences.
    """

    cleaned = text.strip()

    try:
        parsed = json.loads(cleaned)

    except json.JSONDecodeError:
        # Remove a Markdown code fence if the model added one.
        if cleaned.startswith("```"):
            lines = cleaned.splitlines()

            if lines and lines[0].strip().startswith("```"):
                lines = lines[1:]

            if lines and lines[-1].strip() == "```":
                lines = lines[:-1]

            cleaned = "\n".join(lines).strip()

        try:
            parsed = json.loads(cleaned)

        except json.JSONDecodeError:
            # Last-resort extraction of the outermost JSON object.
            start = cleaned.find("{")
            end = cleaned.rfind("}")

            if start == -1 or end == -1 or end <= start:
                raise ValueError(
                    "The LLM response did not contain a JSON object."
                )

            parsed = json.loads(cleaned[start : end + 1])

    if not isinstance(parsed, dict):
        raise ValueError("The LLM response must be a JSON object.")

    return parsed


def validate_person_answers(
    *,
    answers: dict[str, Any],
    survey,
) -> None:
    """
    Ensure the response has exactly the survey questions as keys and that every
    answer is plain text.
    """

    expected_ids = {
        question.id
        for question in survey.questions
    }

    actual_ids = set(answers.keys())

    missing_ids = expected_ids - actual_ids
    extra_ids = actual_ids - expected_ids

    if missing_ids:
        raise ValueError(
            f"Missing survey answers: {sorted(missing_ids)}"
        )

    if extra_ids:
        raise ValueError(
            f"Unexpected survey answers: {sorted(extra_ids)}"
        )

    for question_id, answer in answers.items():
        if not isinstance(answer, str):
            raise ValueError(
                f"Answer for {question_id!r} must be a string, "
                f"but received {type(answer).__name__}."
            )

        if not answer.strip():
            raise ValueError(
                f"Answer for {question_id!r} cannot be empty."
            )


def complete_one_person_survey(
    *,
    llm: OpenAIChatLLM,
    person: dict[str, str],
    survey: SurveyDefinition,
    max_attempts: int = 3,
) -> dict[str, str]:
    """
    Complete the survey for one person.

    Each call to llm.complete() is independent. No conversation history is
    passed between people.
    """

    base_prompt = build_person_survey_prompt(
        person=person,
        survey=survey,
    )

    last_error: Exception | None = None

    for attempt in range(1, max_attempts + 1):
        if attempt == 1:
            user_prompt = base_prompt
        else:
            user_prompt = f"""
Your previous response failed validation.

Validation error:
{last_error}

Please try again. Return only one valid JSON object. Every survey answer
must be a plain text string, not a dictionary or list.

{base_prompt}
"""

        request = LLMRequest(
            task_id=(
                f"{person_survey.id}:"
                f"{person['id']}:"
                f"attempt_{attempt}"
            ),
            system_prompt=PERSON_SURVEY_SYSTEM_PROMPT,
            user_prompt=user_prompt,
            max_tokens=4_000,
            temperature=1,
            attempt=1
        )

        try:
            reply = llm.complete(request)

            parsed_answers = extract_json_object(reply.text)

            validate_person_answers(
                answers=parsed_answers,
                survey=survey,
            )

            # The validation above guarantees that all values are strings.
            return {
                question_id: answer
                for question_id, answer in parsed_answers.items()
            }

        except Exception as exc:
            last_error = exc

    raise RuntimeError(
        f"Could not complete the survey for {person['id']} "
        f"after {max_attempts} attempts. Last error: {last_error}"
    )


def response_to_dict(response: SurveyResponse) -> dict[str, Any]:
    """
    Convert a SurveyResponse object into a JSON-compatible dictionary.
    """

    return {
        "entity_id": response.entity_id,
        "entity_type": response.entity_type,
        "survey_id": response.survey_id,
        "answers": response.answers,
    }


def save_person_responses(
    *,
    output_path: str | Path,
    people: list[dict[str, str]],
    responses: list[SurveyResponse],
) -> None:
    """
    Save the current survey results to JSON.
    """

    output = {
        "survey_id": person_survey.id,
        "respondent_type": "person",
        "people": people,
        "responses": [
            response_to_dict(response)
            for response in responses
        ],
    }

    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    with output_path.open("w", encoding="utf-8") as file:
        json.dump(
            output,
            file,
            indent=2,
            ensure_ascii=False,
        )


def generate_person_survey_responses(
    *,
    model: str,
    people: list[dict[str, str]],
    survey: SurveyDefinition,
    output_path: str | Path = "person_survey_responses.json",
) -> list[SurveyResponse]:
    """
    Generate independent survey responses for all people.

    Results are saved after every person so that partial progress is preserved.
    """

    llm = OpenAIChatLLM.from_environment(model=model)

    responses: list[SurveyResponse] = []

    for index, person in enumerate(people, start=1):
        print(
            f"[{index}/{len(people)}] "
            f"Completing survey for {person['id']} "
            f"({person['name']})..."
        )

        answers = complete_one_person_survey(
            llm=llm,
            person=person,
            survey=survey,
        )

        response = SurveyResponse(
            entity_id=person["id"],
            entity_type="person",
            survey_id=survey.id,
            answers=answers,
        )

        responses.append(response)

        # Save after every successful response.
        save_person_responses(
            output_path=output_path,
            people=people,
            responses=responses,
        )

    print(
        f"Saved {len(responses)} person survey responses "
        f"to {output_path}"
    )

    return responses


